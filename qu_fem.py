class z_i(Bloq):
  def __init__(self, n, i):
    self.n = n
    self.i = i
  @property
  def signature(self):
    return Signature([Register("point",QAny(self.n))])
  def build_composite_bloq(self, bb, *, point):
    point_array = bb.split(point)
    point_array[self.n - self.i -1] = bb.add(ZGate(),q = point_array[self. n - self.i -1])
    point = bb.join(point_array, dtype = QAny(self.n))
    return {"point": point}

def build_x(n, h, x_l_i):
  coeff_1 = h * (x_l_i+ 1)/2
  coeff_2 = h
  N = 2**n
  coeffs = [coeff_1, h * (N-1)/2]
  unitaries = [Unitary(Identity(n)),Unitary(Identity(n))]
  for i in range(n):
    coeffs.append(-(coeff_2 * 0.5 * (2**i)))
    unitaries.append(Unitary(z_i(n,i)))
  return LinearCombination(tuple(unitaries),lambd = tuple(coeffs), lambd_bits = 4)


